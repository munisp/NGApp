// AddRule adds a rule to the engine
func (re *RulesEngine) AddRule(rule *Rule) {
	rule.CreatedAt = time.Now()
	rule.UpdatedAt = time.Now()
	re.rules[rule.ID] = rule
	re.logger.Info("Rule added", zap.String("rule_id", rule.ID), zap.String("rule_name", rule.Name))
}

// RemoveRule removes a rule from the engine
func (re *RulesEngine) RemoveRule(ruleID string) {
	delete(re.rules, ruleID)
	re.logger.Info("Rule removed", zap.String("rule_id", ruleID))
}

// EnableRule enables a rule
func (re *RulesEngine) EnableRule(ruleID string) {
	if rule, ok := re.rules[ruleID]; ok {
		rule.Enabled = true
		rule.UpdatedAt = time.Now()
	}
}

// DisableRule disables a rule
func (re *RulesEngine) DisableRule(ruleID string) {
	if rule, ok := re.rules[ruleID]; ok {
		rule.Enabled = false
		rule.UpdatedAt = time.Now()
	}
}

// EvaluateRules evaluates all rules against the feature vector
func (re *RulesEngine) EvaluateRules(ctx context.Context, features map[string]float64) []RuleEvaluationResult {
	var results []RuleEvaluationResult

	for _, rule := range re.rules {
		if !rule.Enabled {
			continue
		}

		if re.evaluateRule(rule, features) {
			results = append(results, RuleEvaluationResult{
				RuleID:      rule.ID,
				RuleName:    rule.Name,
				Matched:     true,
				Action:      rule.Action,
				Severity:    rule.Severity,
				Description: rule.Description,
				MatchedAt:   time.Now(),
			})
		}
	}

	// Evaluate AI-generated rules
	for _, aiRule := range re.aiRules {
		if !aiRule.Enabled {
			continue
		}

		if re.evaluateRule(&aiRule.Rule, features) {
			results = append(results, RuleEvaluationResult{
				RuleID:      aiRule.ID,
				RuleName:    aiRule.Name,
				Matched:     true,
				Action:      aiRule.Action,
				Severity:    aiRule.Severity,
				Description: aiRule.Description,
				MatchedAt:   time.Now(),
			})
		}
	}

	return results
}

// evaluateRule evaluates a single rule
func (re *RulesEngine) evaluateRule(rule *Rule, features map[string]float64) bool {
	if len(rule.Conditions) == 0 {
		return false
	}

	// Evaluate conditions with AND/OR logic
	result := true
	for i, condition := range rule.Conditions {
		conditionResult := re.evaluateCondition(condition, features)

		if i == 0 {
			result = conditionResult
		} else {
			switch condition.Logic {
			case "AND":
				result = result && conditionResult
			case "OR":
				result = result || conditionResult
			default:
				result = result && conditionResult
			}
		}
	}

	return result
}

// evaluateCondition evaluates a single condition
func (re *RulesEngine) evaluateCondition(condition RuleCondition, features map[string]float64) bool {
	featureValue, exists := features[condition.Field]
	if !exists {
		return false
	}

	switch condition.Operator {
	case "eq":
		return re.compareEqual(featureValue, condition.Value)
	case "ne":
		return !re.compareEqual(featureValue, condition.Value)
	case "gt":
		return re.compareGreater(featureValue, condition.Value)
	case "gte":
		return re.compareGreaterOrEqual(featureValue, condition.Value)
	case "lt":
		return re.compareLess(featureValue, condition.Value)
	case "lte":
		return re.compareLessOrEqual(featureValue, condition.Value)
	case "in":
		return re.compareIn(featureValue, condition.Value)
	case "regex":
		return re.compareRegex(featureValue, condition.Value)
	default:
		return false
	}
}

func (re *RulesEngine) compareEqual(a float64, b interface{}) bool {
	switch v := b.(type) {
	case float64:
		return a == v
	case int:
		return a == float64(v)
	case bool:
		return (a == 1.0) == v
	default:
		return false
	}
}

func (re *RulesEngine) compareGreater(a float64, b interface{}) bool {
	switch v := b.(type) {
	case float64:
		return a > v
	case int:
		return a > float64(v)
	default:
		return false
	}
}

func (re *RulesEngine) compareGreaterOrEqual(a float64, b interface{}) bool {
	switch v := b.(type) {
	case float64:
		return a >= v
	case int:
		return a >= float64(v)
	default:
		return false
	}
}

func (re *RulesEngine) compareLess(a float64, b interface{}) bool {
	switch v := b.(type) {
	case float64:
		return a < v
	case int:
		return a < float64(v)
	default:
		return false
	}
}

func (re *RulesEngine) compareLessOrEqual(a float64, b interface{}) bool {
	switch v := b.(type) {
	case float64:
		return a <= v
	case int:
		return a <= float64(v)
	default:
		return false
	}
}

func (re *RulesEngine) compareIn(a float64, b interface{}) bool {
	switch v := b.(type) {
	case []float64:
		for _, val := range v {
			if a == val {
				return true
			}
		}
	case []int:
		for _, val := range v {
			if a == float64(val) {
				return true
			}
		}
	}
	return false
}

func (re *RulesEngine) compareRegex(a float64, b interface{}) bool {
	pattern, ok := b.(string)
	if !ok {
		return false
	}
	matched, _ := regexp.MatchString(pattern, string(rune(int(a))))
	return matched
}

// AddAIGeneratedRule adds an AI-generated rule
func (re *RulesEngine) AddAIGeneratedRule(rule *AIGeneratedRule) {
	rule.GeneratedAt = time.Now()
	rule.CreatedAt = time.Now()
	rule.UpdatedAt = time.Now()
	rule.Type = RuleTypeAI
	re.aiRules = append(re.aiRules, rule)
	re.logger.Info("AI-generated rule added",
		zap.String("rule_id", rule.ID),
		zap.Float64("confidence", rule.Confidence))
}

// GetAllRules returns all rules
func (re *RulesEngine) GetAllRules() []*Rule {
	rules := make([]*Rule, 0, len(re.rules))
	for _, rule := range re.rules {
		rules = append(rules, rule)
	}
	return rules
}

// GetRule returns a specific rule
func (re *RulesEngine) GetRule(ruleID string) (*Rule, bool) {
	rule, ok := re.rules[ruleID]
	return rule, ok
}

// GetMatchedRules converts evaluation results to matched rules for response
func (re *RulesEngine) GetMatchedRules(results []RuleEvaluationResult) []models.MatchedRule {
	matched := make([]models.MatchedRule, len(results))
	for i, result := range results {
		matched[i] = models.MatchedRule{
			RuleID:      result.RuleID,
			RuleName:    result.RuleName,
			RuleType:    string(re.rules[result.RuleID].Type),
			Action:      string(result.Action),
			Severity:    result.Severity,
			Description: result.Description,
			MatchedAt:   result.MatchedAt,
		}
	}
	return matched
}
