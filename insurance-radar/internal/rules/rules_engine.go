// RulesEngine manages fraud detection rules
// Inspired by Stripe Radar's dynamic, AI-generated rules
type RulesEngine struct {
	rules       map[string]*Rule
	ruleGroups  map[string]*RuleGroup
	aiRules     []*AIGeneratedRule
	logger      *zap.Logger
}

// Rule represents a fraud detection rule
type Rule struct {
	ID          string            `json:"id"`
	Name        string            `json:"name"`
	Description string            `json:"description"`
	Type        RuleType          `json:"type"`
	Conditions  []RuleCondition   `json:"conditions"`
	Action      RuleAction        `json:"action"`
	Severity    string            `json:"severity"`
	Enabled     bool              `json:"enabled"`
	Priority    int               `json:"priority"`
	CreatedAt   time.Time         `json:"created_at"`
	UpdatedAt   time.Time         `json:"updated_at"`
	Metadata    map[string]string `json:"metadata"`
}

// RuleType represents the type of rule
type RuleType string

const (
	RuleTypeStatic    RuleType = "static"
	RuleTypeDynamic   RuleType = "dynamic"
	RuleTypeAI        RuleType = "ai_generated"
	RuleTypeVelocity  RuleType = "velocity"
	RuleTypeBlacklist RuleType = "blacklist"
	RuleTypeWhitelist RuleType = "whitelist"
)

// RuleCondition represents a condition in a rule
type RuleCondition struct {
	Field    string      `json:"field"`
	Operator string      `json:"operator"`
	Value    interface{} `json:"value"`
	Logic    string      `json:"logic"` // AND, OR
}

// RuleAction represents the action to take when a rule matches
type RuleAction string

const (
	RuleActionBlock   RuleAction = "block"
	RuleActionReview  RuleAction = "review"
	RuleActionFlag    RuleAction = "flag"
	RuleActionAllow   RuleAction = "allow"
	RuleActionChallenge RuleAction = "challenge"
)

// RuleGroup represents a group of related rules
type RuleGroup struct {
	ID          string   `json:"id"`
	Name        string   `json:"name"`
	Description string   `json:"description"`
	RuleIDs     []string `json:"rule_ids"`
	Enabled     bool     `json:"enabled"`
}

// AIGeneratedRule represents a rule generated by AI
type AIGeneratedRule struct {
	Rule
	GeneratedAt    time.Time `json:"generated_at"`
	ModelVersion   string    `json:"model_version"`
	Confidence     float64   `json:"confidence"`
	PerformanceMetrics struct {
		Precision float64 `json:"precision"`
		Recall    float64 `json:"recall"`
		F1Score   float64 `json:"f1_score"`
	} `json:"performance_metrics"`
}

// RuleEvaluationResult represents the result of rule evaluation
type RuleEvaluationResult struct {
	RuleID      string     `json:"rule_id"`
	RuleName    string     `json:"rule_name"`
	Matched     bool       `json:"matched"`
	Action      RuleAction `json:"action"`
	Severity    string     `json:"severity"`
	Description string     `json:"description"`
	MatchedAt   time.Time  `json:"matched_at"`
}

// NewRulesEngine creates a new rules engine
func NewRulesEngine(logger *zap.Logger) *RulesEngine {
	engine := &RulesEngine{
		rules:      make(map[string]*Rule),
		ruleGroups: make(map[string]*RuleGroup),
		aiRules:    make([]*AIGeneratedRule, 0),
		logger:     logger,
	}

	// Initialize default rules
	engine.initializeDefaultRules()

	return engine
}

